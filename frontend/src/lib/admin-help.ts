export function searchHelpSections(query: string): HelpSection[] {
  const q = query.trim().toLowerCase();
  if (!q) return HELP_SECTIONS;
  return HELP_SECTIONS.filter((s) => {
    const hay = [s.title, s.summary, s.group, ...s.keywords, ...s.blocks.map(blockText)].join("\n").toLowerCase();
    return hay.includes(q);
  });
}

function blockText(b: HelpBlock): string {
  if (b.type === "p" || b.type === "callout") return b.text;
  if (b.type === "steps" || b.type === "ul") return b.items.join(" ");
  if (b.type === "table") return [...b.headers, ...b.rows.flat()].join(" ");
  if (b.type === "links") return b.items.map((i) => i.label).join(" ");
  return "";
}
